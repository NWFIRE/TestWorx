// Generates a review checklist, not an authorization verdict.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
function walk(dir) { return fs.readdirSync(dir, {withFileTypes:true}).flatMap(e => e.isDirectory() ? walk(path.join(dir,e.name)) : [path.join(dir,e.name)]); }
const files = walk(path.join(root,'apps/web/src/app')).filter(f => /(?:page|route|actions)\.tsx?$/.test(path.basename(f)));
const rows = files.sort().map(file => {
  const source = fs.readFileSync(file,'utf8');
  const signals = ['auth(', 'requireRole(', 'tenantId', 'requireSupportOperator(', 'token', 'CRON_SECRET'].filter(s => source.includes(s));
  return `| \`${path.relative(root,file).replaceAll('\\','/')}\` | ${signals.join(', ') || 'Inherited/delegated context: trace required'} | Pending full service-chain review |`;
});
fs.writeFileSync(path.join(root,'docs/subscriber-route-inventory.md'), '# Subscriber surface inventory\n\nGenerated by `node scripts/staging/inventory-surfaces.cjs`. Signals are navigation aids, NOT evidence that authorization is correct. Layout guards and service queries require manual tracing. See the staging handoff for checks actually run.\n\n| Entry point | Context signals | Review status |\n| --- | --- | --- |\n'+rows.join('\n')+'\n');
console.log(`${rows.length} page, action and route entry points inventoried.`);
